//! Ошибки инфраструктуры транзакционной почты.
//!
//! Одна ошибка на все слои: транспорт Resend, подпись вебхука, разбор
//! события и шаблоны. Варианты различаются не «где случилось», а «что
//! делать вызывающему»: повторить позже ([`MailError::Unavailable`],
//! [`MailError::Timeout`]), выждать ([`MailError::RateLimited`]),
//! остановиться и позвать человека ([`MailError::Unauthorized`]) или
//! признать письмо неотправляемым ([`MailError::Rejected`]).
//!
//! Секреты (`RESEND_API_KEY`, signing secret) в сообщения ошибок не
//! попадают: тела ответов провайдера проходят через `sanitize_body`
//! (короткий префикс, обрезанный по границе символа).

use thiserror::Error;

/// Ошибка отправки письма, проверки вебхука или рендера шаблона.
#[derive(Debug, Error)]
pub enum MailError {
    /// Провайдер недоступен: сетевая ошибка, 5xx, исчерпаны повторы.
    ///
    /// Письмо не ушло, но может уйти позже — строку в БД положено
    /// вернуть в очередь с backoff, а не помечать окончательно упавшей.
    #[error("mail transport unavailable: {0}")]
    Unavailable(String),
    /// Ошибка аутентификации: 401/403, неверный или отозванный API-ключ.
    ///
    /// Повторы бессмысленны и вредны: ключ чинится руками.
    #[error("mail transport unauthorized: {0}")]
    Unauthorized(String),
    /// Провайдер ограничил частоту (429).
    ///
    /// `retry_after_secs` — подсказка из заголовка `Retry-After`
    /// (секунды или HTTP-date). `None` означает, что провайдер не сказал
    /// ничего: тогда работает собственный backoff воркера.
    #[error("mail rate limited (retry after {retry_after_secs:?} s)")]
    RateLimited {
        /// Через сколько секунд имеет смысл повторить, если провайдер сказал.
        retry_after_secs: Option<i64>,
    },
    /// Провайдер отверг письмо: 400/404/409/422 — адрес, домен, шаблон.
    ///
    /// Повторять нельзя: та же полезная нагрузка даст тот же ответ.
    #[error("mail rejected by provider: {0}")]
    Rejected(String),
    /// Ответ провайдера не разобран: не JSON, нет `id`, неожидаемый 2xx.
    ///
    /// Отдельный вариант нужен, чтобы 200 без `id` не выглядел как
    /// «отправлено»: без provider_id строка не сшивается с вебхуками.
    #[error("mail response decode error: {0}")]
    Decode(String),
    /// Ошибка конфигурации: пустой ключ, невалидный адрес, битый секрет,
    /// отсутствующая переменная шаблона.
    ///
    /// Это баг или недонастроенное окружение, а не сбой сети: письмо не
    /// отправляется и не должно попадать в бесконечный retry.
    #[error("mail config error: {0}")]
    Config(String),
    /// Превышен таймаут одиночного запроса к провайдеру.
    #[error("mail request timed out")]
    Timeout,
    /// Подпись вебхука не сошлась: нет заголовка, чужая подпись, битый
    /// формат.
    #[error("mail webhook signature invalid: {0}")]
    SignatureInvalid(String),
    /// Timestamp вебхука вне допуска — отдельно от «подпись не сошлась»,
    /// чтобы в логах было видно: тело, возможно, подлинное, но запоздалое
    /// (replay или сильный дрейф часов).
    #[error("mail webhook signature expired")]
    SignatureExpired,
}
